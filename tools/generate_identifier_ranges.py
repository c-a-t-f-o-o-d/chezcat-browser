"""Generate the JavaScript identifier ranges from the pinned Unicode 17.0.0 UCD."""
import argparse
import hashlib
from pathlib import Path

SOURCE = "https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"


def ranges(points):
    pairs = []
    for point in sorted(points):
        if pairs and pairs[-1][1] + 1 == point:
            pairs[-1][1] = point
        else:
            pairs.append([point, point])
    return pairs


def table(name, points):
    rows = [f"pub(super) const {name}: &[(u32, u32)] = &["]
    for low, high in ranges(points):
        rows.append(f"    (0x{low:X}, 0x{high:X}),")
    return "\n".join([*rows, "];"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd", type=Path, help=SOURCE)
    args = parser.parse_args()
    data = args.ucd.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        parser.error("Digest differs from Unicode 17.0.0 DerivedCoreProperties.txt")
    properties = {"ID_Start": set(), "ID_Continue": set()}
    for line in data.decode("utf-8").splitlines():
        fields = [part.strip() for part in line.split("#", 1)[0].split(";")]
        if len(fields) != 2 or fields[1] not in properties:
            continue
        ends = fields[0].split("..")
        lo, hi = int(ends[0], 16), int(ends[-1], 16)
        properties[fields[1]].update(range(max(128, lo), hi + 1))
    start, part = properties["ID_Start"], properties["ID_Continue"]
    assert start and start < part
    header = ("// Generated by tools/generate_identifier_ranges.py from Unicode 17.0.0.\n"
              "// DerivedCoreProperties.txt © 2025 Unicode, Inc. See THIRD_PARTY_NOTICES.md.\n"
              f"// {SOURCE}\n// SHA-256 {SHA256}")
    output = Path(__file__).resolve().parents[1] / "src" / "unicode_identifier_ranges.rs"
    with output.open("w", encoding="utf-8", newline="\n") as f:
        f.write("\n\n".join((header, table("START", start), table("CONTINUE_ONLY", part - start))) + "\n")


if __name__ == "__main__":
    main()
